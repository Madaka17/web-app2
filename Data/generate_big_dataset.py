def format_rai_ngan_sqwa(total_sqwa):
    if total_sqwa is None:
        return "ไม่มีที่ดิน (กรรมสิทธิ์ห้องชุด)"
    rai = int(total_sqwa // 400)
    rem = total_sqwa % 400
    ngan = int(rem // 100)
    sqwa = round(rem % 100, 1)
    return f"{rai} ไร่ {ngan} งาน {sqwa} ตร.ว."

